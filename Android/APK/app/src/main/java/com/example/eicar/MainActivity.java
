package com.eicar.test;

import android.os.Bundle;
import android.app.Activity;
import android.widget.TextView;
import android.widget.Toast;
import android.Manifest;
import android.content.pm.PackageManager;
import android.os.Environment;
import android.os.Build;
import androidx.core.app.ActivityCompat;
import androidx.core.content.ContextCompat;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;
import java.io.ByteArrayInputStream;

public class MainActivity extends Activity {
    private static final int REQUEST_CODE = 100;
    private String eicarPayload = "X5O!P%@AP[4\\PZX54(P^)7CC)7}$EICAR-STANDARD-ANTIVIRUS-TEST-FILE!$H+H*";

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        setContentView(R.layout.activity_main);

        TextView tv = findViewById(R.id.textView);
        tv.setText("EICAR Test APK\n\n" + eicarPayload + "\n\nCreating test files...");

        checkPermissions();
    }

    private void checkPermissions() {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
            if (ContextCompat.checkSelfPermission(this, Manifest.permission.WRITE_EXTERNAL_STORAGE)
                    != PackageManager.PERMISSION_GRANTED) {
                ActivityCompat.requestPermissions(this,
                        new String[]{Manifest.permission.WRITE_EXTERNAL_STORAGE},
                        REQUEST_CODE);
            } else {
                createFiles();
            }
        } else {
            createFiles();
        }
    }

    @Override
    public void onRequestPermissionsResult(int requestCode, String[] permissions, int[] grantResults) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults);
        if (requestCode == REQUEST_CODE) {
            if (grantResults.length > 0 && grantResults[0] == PackageManager.PERMISSION_GRANTED) {
                createFiles();
            } else {
                Toast.makeText(this, "Permission denied. Cannot create test files.", Toast.LENGTH_LONG).show();
            }
        }
    }

    private void createFiles() {
        try {
            File downloadsDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS);
            if (!downloadsDir.exists()) {
                downloadsDir.mkdirs();
            }

            createEicarTxt(downloadsDir);
            createEicarCom(downloadsDir);
            createEicarZip(downloadsDir);

            Toast.makeText(this, "Test files created in Downloads folder!", Toast.LENGTH_LONG).show();
        } catch (Exception e) {
            Toast.makeText(this, "Error: " + e.getMessage(), Toast.LENGTH_LONG).show();
        }
    }

    private void createEicarTxt(File dir) throws IOException {
        File file = new File(dir, "eicar.txt");
        try (FileOutputStream fos = new FileOutputStream(file)) {
            fos.write(eicarPayload.getBytes());
        }
    }

    private void createEicarCom(File dir) throws IOException {
        File file = new File(dir, "eicar.com");
        try (FileOutputStream fos = new FileOutputStream(file)) {
            fos.write(eicarPayload.getBytes());
        }
    }

    private void createEicarZip(File dir) throws IOException {
        File zipFile = new File(dir, "eicar.zip");
        try (FileOutputStream fos = new FileOutputStream(zipFile);
             ZipOutputStream zos = new ZipOutputStream(fos)) {

            ZipEntry entry = new ZipEntry("eicar.txt");
            zos.putNextEntry(entry);
            zos.write(eicarPayload.getBytes());
            zos.closeEntry();
        }
    }
}